import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
const auth = await import('../agent/lib/private-auth.ts');
const username = randomBytes(12).toString('hex');
const password = randomBytes(32).toString('base64url');
delete process.env.PRIVATE_LOGIN_USERNAME;
delete process.env.PRIVATE_LOGIN_PASSWORD;
assert.equal(auth.verifySession(undefined), false);
assert.equal(auth.isLoginConfigured(), false);
process.env.PRIVATE_LOGIN_USERNAME = username;
process.env.PRIVATE_LOGIN_PASSWORD = password;
assert.equal(auth.isLoginConfigured(), true);
assert.equal(auth.checkCredentials(username, password), true);
assert.equal(auth.checkCredentials(username, randomBytes(32).toString('hex')), false);
assert.equal(auth.checkCredentials('other-user', password), false);
const now = Date.now();
const token = auth.createSession(now);
assert.equal(auth.verifySession(token, now), true);
assert.equal(auth.verifySession(token + 'x', now), false);
const forged = token.slice(0, -1) + (token.endsWith('A') ? 'B' : 'A');
assert.equal(auth.verifySession(forged, now), false);
assert.equal(auth.verifySession(token.replace(/^./, '9'), now), false);
assert.equal(auth.verifySession(token, now + 12 * 60 * 60 * 1000), false);
assert.equal(auth.sessionFromRequest(new Request('https://example.test', {headers: {cookie: `${auth.SESSION_COOKIE}=${token}`}})), true);
assert.equal(auth.sessionFromRequest(new Request('https://example.test')), false);
process.env.PRIVATE_LOGIN_PASSWORD = randomBytes(32).toString('hex');
assert.equal(auth.verifySession(token, now), false);
process.env.PRIVATE_LOGIN_PASSWORD = password;
process.env.PRIVATE_LOGIN_USERNAME = 'changed-user';
assert.equal(auth.verifySession(token, now), false);
process.env.PRIVATE_LOGIN_USERNAME = username;
console.log('PASS: missing config, credentials, signed cookies, tampering, expiry, credential rotation');

process.env.PRIVATE_LOGIN_PASSWORD = randomBytes(8).toString('hex');
assert.equal(auth.isLoginConfigured(), false);
assert.equal(auth.verifySession(token, now), false);
assert.throws(() => auth.createSession());
console.log('PASS: short passwords fail closed');
